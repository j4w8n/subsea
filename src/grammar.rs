#[derive(Debug, PartialEq, Clone)]
pub enum Token {
    Bool(bool),
    Colon,
    Dollar,
    DoubleColon,
    Equals,
    Ident(String),
    LBrace,
    LBracket,
    LParen,
    Minus,
    Mut,
    Number(NumericKind),
    NumberLiteral(String),
    Percent,
    Plus,
    RBrace,
    RBracket,
    RParen,
    Slash,
    Star,
    Text(String),

    Ampersand,
    Comma,
    Directive(String),
    Exit,
    Idiv,
    Jmp,
    Let,
    Literal,
    Mem,
    Period,
    Pointer(String),
    Print,
    Register(String),
    Syscall,
    Udiv,
}

#[derive(Debug, PartialEq, Clone)]
pub enum NumericKind {
    I8(i8),
    I16(i16),
    I32(i32),
    I64(i64),
    Int(i64),
    U8(u8),
    U16(u16),
    U32(u32),
    U64(u64),
    F32(f32),
    F64(f64),
    Float(f64),
}
